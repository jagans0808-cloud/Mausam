// 4. Helper function to fetch mock city data or generate customized fallback
function getMockWeatherData(cityName) {
  if (!cityName) return CITIES_WEATHER_DATA["New Delhi"];
  if (CITIES_WEATHER_DATA[cityName]) {
    return CITIES_WEATHER_DATA[cityName];
  }
  // Case-insensitive lookup
  const matchKey = Object.keys(CITIES_WEATHER_DATA).find(
    (key) => key.toLowerCase() === cityName.toLowerCase()
  );
  if (matchKey) {
    return CITIES_WEATHER_DATA[matchKey];
  }
  return generateFallbackCityData(cityName);
}

